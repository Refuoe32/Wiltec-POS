// Downloads a report as CSV (opens in Excel) or PDF. A report = { title, subtitle, sections:[{ title, head?, rows }] }
function save(blob, filename) {
  const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = filename;
  document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(a.href), 2000);
}
export function exportCSV(name, r) {
  const esc = v => { const s = String(v ?? ''); return /[",\n]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s; };
  const out = ['WilTec Solutions - Mokhotlong, Lesotho', r.title, r.subtitle, ''];
  for (const s of r.sections) {
    out.push(esc(s.title));
    if (s.head) out.push(s.head.map(esc).join(','));
    s.rows.forEach(row => out.push(row.map(esc).join(',')));
    out.push('');
  }
  save(new Blob(['\ufeff' + out.join('\r\n')], { type: 'text/csv;charset=utf-8' }), name + '.csv');
}
const numeric = v => /^-?(M\s)?[\d,]+(\.\d+)?%?$/.test(String(v).trim());
export async function exportPDF(name, r) {
  const { jsPDF } = await import('jspdf');
  const mod = await import('jspdf-autotable');
  const autoTable = [mod.default, mod.autoTable, mod.default?.default, mod.default?.autoTable].find(f => typeof f === 'function');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = doc.internal.pageSize.getWidth(), H = doc.internal.pageSize.getHeight();
  doc.setFillColor(10, 168, 98); doc.rect(0, 0, W, 54, 'F');
  doc.setTextColor(255); doc.setFont('helvetica', 'bold'); doc.setFontSize(16); doc.text('WilTec Solutions', 40, 26);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.text('IT Services, Repairs & Tech Shop - Mokhotlong, Lesotho', 40, 41);
  doc.setTextColor(30, 40, 46); doc.setFont('helvetica', 'bold'); doc.setFontSize(14); doc.text(r.title, 40, 84);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(110); doc.text(doc.splitTextToSize(r.subtitle || '', W - 80), 40, 99);
  let y = 118;
  for (const s of r.sections) {
    if (!s.rows.length) continue;
    if (y > H - 110) { doc.addPage(); y = 50; }
    doc.setFont('helvetica', 'bold'); doc.setFontSize(10.5); doc.setTextColor(30, 40, 46); doc.text(s.title, 40, y);
    const cols = (s.head || s.rows[0]).length, colStyles = {};
    for (let c = 0; c < cols; c++) if (s.rows.every(row => numeric(row[c] ?? ''))) colStyles[c] = { halign: 'right' };
    autoTable(doc, { startY: y + 6, head: s.head ? [s.head] : undefined, body: s.rows.map(row => row.map(v => String(v ?? ''))), margin: { left: 40, right: 40 },
      styles: { fontSize: 8.5, cellPadding: 4, textColor: [30, 40, 46] }, headStyles: { fillColor: [85, 100, 108], textColor: 255 },
      alternateRowStyles: { fillColor: [244, 247, 248] }, columnStyles: colStyles, theme: 'striped',
      didParseCell: d => { if (d.section === 'head' && colStyles[d.column.index]) d.cell.styles.halign = 'right'; } });
    y = doc.lastAutoTable.finalY + 22;
  }
  const n = doc.getNumberOfPages();
  for (let i = 1; i <= n; i++) { doc.setPage(i); doc.setFontSize(8); doc.setTextColor(140); doc.text(`Page ${i} of ${n}`, W - 40, H - 22, { align: 'right' }); doc.text('Generated by WilTec POS', 40, H - 22); }
  doc.save(name + '.pdf');
}
